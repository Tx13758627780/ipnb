// Pre-bakes the ghosted world map used by <WorldMap /> into a tiny TS module.
// Run with: node scripts/build-world-map.mjs
// The projection (Natural Earth 1, centred on 120°E, fitted to a 1000-unit
// wide sphere) is mirrored at runtime by src/components/world-map/projection.ts.
import { geoGraticule, geoNaturalEarth1, geoPath } from "d3-geo";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const res = process.argv[2] ?? "110m";
const topo = require(`world-atlas/land-${res}.json`);
const land = feature(topo, topo.objects.land);
const WIDTH = 1000;
const CENTER = 120;
const projection = geoNaturalEarth1()
  .rotate([-CENTER, 0])
  .fitWidth(WIDTH, { type: "Sphere" });
const path = geoPath(projection).digits(1);
const [tx, ty] = projection.translate();
const sphere = geoPath(projection).bounds({ type: "Sphere" });
const frame = `// Generated by scripts/build-world-map.mjs. Do not edit.
// Projection frame only (tiny), so pages can place points without loading land.
export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${Math.round(sphere[1][1] * 10) / 10};
export const MAP_CENTER = ${CENTER};
export const MAP_SCALE = ${projection.scale()};
export const MAP_TRANSLATE = [${tx}, ${ty}] as const;
// Reference points for tests: [lon, lat, x, y].
export const PROJECTION_SAMPLES = ${JSON.stringify(
  [
    [121.47, 31.23],
    [-122.42, 37.77],
    [8.68, 50.11],
    [151.2, -33.87],
  ].map(([lon, lat]) => [
    lon,
    lat,
    ...projection([lon, lat]).map((v) => Math.round(v * 100) / 100),
  ]),
)};
`;
const out = `// Generated by scripts/build-world-map.mjs (world-atlas land-${res}). Do not edit.
export const LAND_PATH =
  ${JSON.stringify(path(land))};
export const GRATICULE_PATH =
  ${JSON.stringify(path(geoGraticule().step([20, 20])()))};
export const SPHERE_PATH = ${JSON.stringify(path({ type: "Sphere" }))};
`;
writeFileSync("src/components/world-map/frame.ts", frame);
writeFileSync("src/components/world-map/geometry.ts", out);
console.log("geometry.ts", out.length, "bytes");
